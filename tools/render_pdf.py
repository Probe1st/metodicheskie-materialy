def _student_outcome(outcome: str) -> str:
    return _OUTCOME_VERB_PATTERN.sub(
        lambda match: _OUTCOME_INFINITIVES[match.group().casefold()], outcome
    )


def _sources_for(
    session: Session, source_keys: tuple[str, ...] | None = None
) -> tuple[tuple[str, str], ...]:
    if source_keys is None:
        from tools.generate_course import SOURCES, THEORY

        source_keys = THEORY[session.number].sources
    else:
        from tools.generate_course import SOURCES

    return tuple(SOURCES[key] for key in source_keys)

def _register_font() -> None:
    if FONT_NAME not in pdfmetrics.getRegisteredFontNames():
        if not FONT_PATH.is_file():
            raise RuntimeError(f"Не найден Unicode-шрифт для презентации: {FONT_PATH}")
        pdfmetrics.registerFont(TTFont(FONT_NAME, str(FONT_PATH)))


