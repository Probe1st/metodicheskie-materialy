def _validate_content() -> None:
    theory_numbers = {session.number for session in SESSIONS if session.kind == "theory"}
    practice_numbers = {session.number for session in SESSIONS if session.kind == "practice"}
    if set(THEORY) != theory_numbers or set(PRACTICE) != practice_numbers:
        raise RuntimeError("Данные содержания не соответствуют манифесту занятий")


def generate(output_root: Path) -> None:
    """Create a clean 49-session HTML package at ``output_root``."""
    _validate_content()
    replacement_root = output_root.with_name(f".{output_root.name}.replacement")
    if replacement_root.exists():
        shutil.rmtree(replacement_root)
    replacement_root.mkdir(parents=True)

    for session in SESSIONS:
        folder = replacement_root / _folder_name(session)
        if session.kind == "theory":
            focus = THEORY[session.number]
            pages = (
                (
                    "metodicheskij-material.html",
                    _page_title(session, "методический материал"),
                    _theory_material(session, focus),
                ),
                (
                    "prakticheskie-zadaniya.html",
                    _page_title(session, "практические задания"),
                    _theory_tasks(session, focus),
                ),
                (
                    "domashnee-zadanie.html",
                    _page_title(session, "самостоятельное задание"),
                    _homework(session, focus.homework),
                ),
            )
            source_keys = focus.sources
        else:
            focus = PRACTICE[session.number]
            pages = (
                (
                    "prakticheskaya-rabota.html",
                    _page_title(session, "практическая работа"),
                    _practice_work(session, focus),
                ),
                (
                    "prakticheskie-zadaniya.html",
                    _page_title(session, "практические задания"),
                    _practice_tasks(session, focus),
                ),
                (
                    "domashnee-zadanie.html",
                    _page_title(session, "самостоятельное задание"),
                    _homework(session, focus.homework),
                ),
            )
            source_keys = focus.sources

        for filename, title, body in pages:
            write_html(folder / filename, render_page(title, body, _source_list(source_keys)))
        if session.kind == "theory":
            render_presentation(session, folder / "prezentaciya.pdf")

    if output_root.exists():
        shutil.rmtree(output_root)
    replacement_root.replace(output_root)


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Создать HTML-комплект материалов")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT_ROOT)
    return parser.parse_args()


if __name__ == "__main__":
    arguments = _parse_args()
    generate(arguments.output)
    print(f"Создан HTML-комплект: {arguments.output}")
